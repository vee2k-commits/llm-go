function tune(rows, idx) {
  var W = 112, r, i;
  var out = [];
  for (r = 0; r < ROWS; r++) {
    var s = rows[r];
    var fill = r >= 15 ? "#" : ".";
    while (s.length < W) s += fill;
    out.push(s.split(""));
  }
  var fixes = TUNE[idx] || [];
  for (i = 0; i < fixes.length; i++) out[fixes[i][0]][fixes[i][1]] = fixes[i][2];
  /* every page ends on a flag pennant, planted on solid ground */
  var fc = FLAG_COL[idx];
  out[14][fc] = "f";
  out[15][fc] = "#";
  /* pits must fall through the whole page depth (no invisible floors) */
  var c;
  for (c = 0; c < W; c++) {
    if (out[15][c] === ".") { out[16][c] = "."; out[17][c] = "."; }
  }
  for (r = 0; r < ROWS; r++) out[r] = out[r].join("");
  return out;
}

/* ------------------------------------------------------------------------ *
 * Parser — ASCII page → tile grid + entity lists. Seeded, deterministic.
 * ------------------------------------------------------------------------ */
function parse(def, idx) {
  var W = 0, r, i;
  var tunedRows = tune(def.rows, idx);
  for (r = 0; r < ROWS; r++) W = Math.max(W, tunedRows[r].length);
  var solid = [], spikes = [];
  for (r = 0; r < ROWS; r++) {
    solid.push(new Array(W).fill(false));
    spikes.push(new Array(W).fill(false));
  }
  var o = {
    idx: idx, name: def.name, seed: def.seed, hint: def.hint,
    palette: PALETTES[idx], w: W, h: ROWS,
    chars: tunedRows,
    solid: solid, spikes: spikes, blocks: {},
    coins: [], stars: [], enemies: [], springs: [], movers: [],
    flags: [], checkpoint: null, flag: null, spawn: { x: 2, y: 13 }
  };
  function ch(r, c) {
    if (r < 0 || r >= ROWS || c < 0 || c >= W) return ".";
    return tunedRows[r].charAt(c) || ".";
  }
  for (r = 0; r < ROWS; r++) {
    for (var c = 0; c < W; c++) {
      var k = ch(r, c);
      if (k === "#") solid[r][c] = true;
      else if (k === "t" || k === "T") solid[r][c] = true;
      else if (k === "X" || k === "B" || k === "?") {
        solid[r][c] = true;
        o.blocks[r + "," + c] = { r: r, c: c, kind: k, used: false, bump: 0 };
      }
      else if (k === "^") spikes[r][c] = true;
      else if (k === "C") o.coins.push({ x: c + 0.5, y: r + 0.55, got: false, seed: "coin" + r + "_" + c });
      else if (k === "*") o.stars.push({ x: c + 0.5, y: r + 0.5, got: false, seed: "star" + r + "_" + c });
      else if (k === "E") o.enemies.push({ x: c + 0.5, y: r + 1 });
      else if (k === "s") o.springs.push({ x: c, y: r, compress: 0, step: 0 });
      else if (k === "M") o.movers.push({ c: c, r: r, axis: "h", range: 3, speed: 0.55, seed: r + "_" + c, x: 0, y: 0, px: 0, py: 0 });
      else if (k === "V") o.movers.push({ c: c, r: r, axis: "v", range: 2, speed: 0.5, seed: r + "_" + c, x: 0, y: 0, px: 0, py: 0 });
      else if (k === "O") o.movers.push({ c: c, r: r, axis: "o", range: 2, speed: 0.5, seed: r + "_" + c, x: 0, y: 0, px: 0, py: 0 });
      else if (k === "F") o.flags.push({ x: c + 0.5, y: r + 1, active: false, seed: "cp" + c });
      else if (k === "f") o.flag = { x: c + 0.5, y: r + 1 };
    }
  }
  if (!o.flags.length) o.flags.push({ x: 6.5, y: 15, active: false, seed: "cp0" });
  o.checkpoint = o.flags[0];
  /* widest gap (for HUD/telemetry, not pressure — there are no timers) */
  o.maxGap = 0;
  var run = 0;
  for (var c2 = 0; c2 < W; c2++) {
    var floorHere = false;
    for (r = 0; r < ROWS; r++) if (solid[r][c2]) { floorHere = true; break; }
    if (!floorHere) { run++; o.maxGap = Math.max(o.maxGap, run); } else run = 0;
  }
  return o;
}

function all() {
  var out = [];
  for (var i = 0; i < LEVELS.length; i++) out.push(parse(LEVELS[i], i));
  return out;
}

